export function placeName(latDeg, lonDeg) {
  let best = null, bd = 1e9;
  const cl = Math.cos(latDeg * Math.PI / 180);
  for (const [n, la, lo] of PLACES) {
    let dl = lonDeg - lo; while (dl > 180) dl -= 360; while (dl < -180) dl += 360;
    const d = (la - latDeg) ** 2 + (dl * cl) ** 2;
    if (d < bd) { bd = d; best = n; }
  }
  return best;
}
